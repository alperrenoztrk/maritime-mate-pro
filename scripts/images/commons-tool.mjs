#!/usr/bin/env node
/**
 * Wikimedia Commons helper used by .github/workflows/commons-images.yml.
 *
 * The development sandbox cannot reach Wikimedia, so candidate images are
 * looked up and downloaded on a GitHub runner and come back as a workflow
 * artifact. Nothing is committed by the workflow: every image is opened and
 * checked by a person before it is copied into src/assets.
 *
 * Two modes:
 *
 *   node scripts/images/commons-tool.mjs candidates <queries.json> <outDir>
 *     For each query (a Commons category or a search string) list files with a
 *     free licence and enough resolution, skip anything tagged as AI-generated,
 *     and save a small preview of each plus candidates.json with the metadata.
 *
 *   node scripts/images/commons-tool.mjs fetch <manifest.json> <outDir>
 *     Download the chosen files (rasters scaled to `width`, SVGs as originals)
 *     and write credits.json with source, author and licence for each.
 *
 * Only Public Domain, CC0, CC BY and CC BY-SA files are accepted.
 */
import fs from "node:fs";
import path from "node:path";

const API = "https://commons.wikimedia.org/w/api.php";
const UA =
  "MarinersBookImageAudit/1.0 (https://github.com/alperrenoztrk/maritime-mate-pro; nauticalleapapps@gmail.com)";
const ALLOWED_LICENSE = /^(public domain|pd|cc0|attribution|cc[ -]by([ -]sa)?([ -][\d.]+.*)?)$/i;
const AI_MARKERS = /(ai[- ]generated|generated by ai|artificial intelligence|midjourney|dall[- ]?e|stable diffusion|text-to-image)/i;
const RASTER_MIN = 1200; // shortest acceptable long side for photos/rasters
const PREVIEW_WIDTH = 480;
const THROTTLE_MS = 700;

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const strip = (html) => (html || "").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60);

async function api(params) {
  const url = `${API}?format=json&formatversion=2&${new URLSearchParams(params)}`;
  for (let attempt = 0; attempt < 5; attempt++) {
    const res = await fetch(url, { headers: { "User-Agent": UA } });
    const text = await res.text();
    try {
      return JSON.parse(text);
    } catch {
      await sleep(2500 * (attempt + 1));
    }
  }
  throw new Error(`Commons API did not answer: ${JSON.stringify(params).slice(0, 200)}`);
}

async function download(url, dest) {
  let lastError;
  for (let attempt = 0; attempt < 5; attempt++) {
    if (attempt) await sleep(3000 * attempt);
    try {
      const res = await fetch(url, { headers: { "User-Agent": UA } });
      if (!res.ok) {
        lastError = new Error(`HTTP ${res.status} ${url}`);
        if (res.status === 404) break;
        continue;
      }
      const buf = Buffer.from(await res.arrayBuffer());
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.writeFileSync(dest, buf);
      return buf.length;
    } catch (err) {
      lastError = err;
    }
  }
  throw lastError;
}

function describe(page) {
  const ii = page.imageinfo?.[0];
  if (!ii) return null;
  const em = ii.extmetadata ?? {};
  const categories = (page.categories ?? []).map((c) => c.title.replace(/^Category:/, ""));
  return {
    title: page.title.replace(/^File:/, ""),
    page: `https://commons.wikimedia.org/wiki/${encodeURIComponent(page.title.replace(/ /g, "_"))}`,
    width: ii.width,
    height: ii.height,
    mime: ii.mime,
    url: ii.url,
    thumb: ii.thumburl,
    license: strip(em.LicenseShortName?.value),
    artist: strip(em.Artist?.value).slice(0, 120),
    credit: strip(em.Credit?.value).slice(0, 160),
    description: strip(em.ImageDescription?.value).slice(0, 400),
    date: strip(em.DateTimeOriginal?.value || em.DateTime?.value).slice(0, 40),
    categories,
  };
}

function rejectReason(info) {
  if (!info) return "no imageinfo";
  if (!ALLOWED_LICENSE.test(info.license)) return `licence "${info.license}"`;
  const haystack = `${info.title} ${info.description} ${info.categories.join(" ")}`;
  if (AI_MARKERS.test(haystack)) return "AI-generated marker";
  const isSvg = info.mime === "image/svg+xml";
  if (!isSvg && Math.max(info.width, info.height) < RASTER_MIN) return `too small ${info.width}x${info.height}`;
  if (!/^image\/(jpeg|png|svg\+xml|webp)$/.test(info.mime)) return `mime ${info.mime}`;
  return null;
}

const INFO_PROPS = {
  prop: "imageinfo|categories",
  iiprop: "url|size|mime|extmetadata",
  iiurlwidth: String(PREVIEW_WIDTH),
  cllimit: "max",
};

async function listQuery(q) {
  const limit = String(q.limit ?? 40);
  if (q.category) {
    return api({
      action: "query",
      generator: "categorymembers",
      gcmtitle: `Category:${q.category}`,
      gcmtype: "file",
      gcmlimit: limit,
      ...INFO_PROPS,
    });
  }
  if (q.titles) {
    return api({ action: "query", titles: q.titles.map((t) => `File:${t}`).join("|"), ...INFO_PROPS });
  }
  return api({
    action: "query",
    generator: "search",
    gsrsearch: q.search,
    gsrnamespace: "6",
    gsrlimit: limit,
    ...INFO_PROPS,
  });
}

async function candidates(queriesFile, outDir) {
  const queries = JSON.parse(fs.readFileSync(queriesFile, "utf8"));
  const result = [];
  for (const q of queries) {
    const label = q.id;
    let json;
    try {
      json = await listQuery(q);
    } catch (err) {
      result.push({ id: label, error: String(err) });
      continue;
    }
    const pages = json.query?.pages ?? [];
    const accepted = [];
    const rejected = [];
    for (const page of pages) {
      const info = describe(page);
      const why = rejectReason(info);
      if (why) {
        rejected.push({ title: page.title, why });
        continue;
      }
      accepted.push(info);
    }
    accepted.sort((a, b) => b.width * b.height - a.width * a.height);
    const keep = accepted.slice(0, q.max ?? 24);
    let n = 0;
    for (const info of keep) {
      n += 1;
      const preview = path.join(outDir, "previews", label, `${String(n).padStart(2, "0")}.jpg`);
      info.preview = path.relative(outDir, preview);
      try {
        // SVG thumburl is already a PNG render; keep the .jpg name, the viewer sniffs the type.
        await download(info.thumb || info.url, preview);
      } catch (err) {
        info.previewError = String(err);
      }
      await sleep(THROTTLE_MS / 2);
    }
    result.push({ id: label, query: q, accepted: keep, rejectedCount: rejected.length, rejected: rejected.slice(0, 40) });
    console.log(`${label}: ${keep.length} kept, ${rejected.length} rejected`);
    await sleep(THROTTLE_MS);
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "candidates.json"), JSON.stringify(result, null, 1));
}

async function fetchChosen(manifestFile, outDir) {
  const manifest = JSON.parse(fs.readFileSync(manifestFile, "utf8"));
  const credits = [];
  const failures = [];
  for (const entry of manifest) {
    const params = {
      action: "query",
      titles: `File:${entry.commons}`,
      prop: "imageinfo|categories",
      iiprop: "url|size|mime|extmetadata",
      cllimit: "max",
      ...(entry.width ? { iiurlwidth: String(entry.width) } : {}),
    };
    const json = await api(params);
    const page = json.query?.pages?.[0];
    const info = page ? describe(page) : null;
    const why = info && !ALLOWED_LICENSE.test(info.license) ? `licence "${info.license}"` : info ? null : "not found";
    if (why) {
      failures.push(`${entry.commons}: ${why}`);
      continue;
    }
    const isSvg = info.mime === "image/svg+xml";
    const url = isSvg || !entry.width ? info.url : page.imageinfo[0].thumburl || info.url;
    const dest = path.join(outDir, entry.dest);
    try {
      const bytes = await download(url, dest);
      credits.push({ ...entry, ...info, bytes });
      console.log(`ok ${entry.dest} ${Math.round(bytes / 1024)} KB ${info.license}`);
    } catch (err) {
      failures.push(`${entry.commons}: ${err}`);
    }
    await sleep(THROTTLE_MS);
  }
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(path.join(outDir, "credits.json"), JSON.stringify({ credits, failures }, null, 1));
  if (failures.length) {
    console.error(failures.join("\n"));
    process.exitCode = 1;
  }
}

const [mode, input, outDir] = process.argv.slice(2);
if (!mode || !input || !outDir) {
  console.error("usage: commons-tool.mjs <candidates|fetch> <input.json> <outDir>");
  process.exit(2);
}
if (mode === "candidates") await candidates(input, outDir);
else if (mode === "fetch") await fetchChosen(input, outDir);
else {
  console.error(`unknown mode ${mode}`);
  process.exit(2);
}
